import { AsyncLocalStorage } from 'node:async_hooks';
import { Pool } from 'pg';
import { DISTRITOS, portariasIniciais } from '../src/domain.ts';

const schema = `
  CREATE TABLE IF NOT EXISTS distritos (
    id TEXT PRIMARY KEY,
    nome TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS unidades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    tipo TEXT NOT NULL,
    distrito_id TEXT NOT NULL REFERENCES distritos(id),
    criado_em TEXT NOT NULL
  );
  CREATE UNIQUE INDEX IF NOT EXISTS unidades_nome_distrito
    ON unidades (LOWER(nome), distrito_id);
  CREATE TABLE IF NOT EXISTS usuarios (
    id TEXT PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    senha_hash TEXT NOT NULL,
    perfil TEXT NOT NULL,
    distrito_id TEXT REFERENCES distritos(id),
    unidade_id INTEGER REFERENCES unidades(id),
    ativo SMALLINT NOT NULL DEFAULT 1 CHECK (ativo IN (0, 1)),
    deve_trocar_senha SMALLINT NOT NULL DEFAULT 0 CHECK (deve_trocar_senha IN (0, 1)),
    criado_em TEXT NOT NULL,
    CHECK (
      (perfil = 'cam' AND distrito_id IS NULL AND unidade_id IS NULL) OR
      (perfil IN ('gg','sna','snb1','snb2') AND distrito_id IS NOT NULL AND unidade_id IS NULL) OR
      (perfil IN ('usf','caps','cecon','mac') AND distrito_id IS NULL AND unidade_id IS NOT NULL)
    )
  );
  CREATE TABLE IF NOT EXISTS sessoes (
    token_hash TEXT PRIMARY KEY,
    usuario_id TEXT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    csrf_token TEXT NOT NULL,
    expira_em BIGINT NOT NULL,
    criada_em TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS sessoes_expiracao ON sessoes(expira_em);
  CREATE TABLE IF NOT EXISTS portarias (
    id TEXT PRIMARY KEY,
    payload TEXT NOT NULL,
    ordem BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
  );
  CREATE TABLE IF NOT EXISTS configuracao (
    chave TEXT PRIMARY KEY,
    valor TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS lancamentos (
    unidade_id INTEGER PRIMARY KEY REFERENCES unidades(id) ON DELETE CASCADE,
    campos TEXT NOT NULL,
    justificativas TEXT NOT NULL,
    perfil_lancamento TEXT,
    enviado SMALLINT NOT NULL DEFAULT 0 CHECK (enviado IN (0, 1)),
    status TEXT NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'em_analise', 'devolvido', 'aprovado')),
    parecer_cam TEXT,
    prazo_resposta TEXT,
    resposta_unidade TEXT,
    revisado_por TEXT REFERENCES usuarios(id),
    revisado_em TEXT,
    atualizado_em TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS historico (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id INTEGER NOT NULL REFERENCES unidades(id) ON DELETE CASCADE,
    sub_id TEXT NOT NULL,
    valor DOUBLE PRECISION NOT NULL,
    submetido_em TEXT NOT NULL,
    aprovado SMALLINT NOT NULL DEFAULT 0 CHECK (aprovado IN (0, 1))
  );
  CREATE INDEX IF NOT EXISTS historico_unidade_indicador ON historico (unidade_id, sub_id, id);
  ALTER TABLE lancamentos ADD COLUMN IF NOT EXISTS perfil_lancamento TEXT;
  CREATE TABLE IF NOT EXISTS auditoria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id TEXT REFERENCES usuarios(id) ON DELETE SET NULL,
    acao TEXT NOT NULL,
    detalhes TEXT NOT NULL,
    criado_em TEXT NOT NULL
  );
`;

function parametrosPostgres(sql) {
  let indice = 0;
  return sql.replace(/\?/g, () => `$${++indice}`);
}

export class BancoPostgres {
  constructor(pool) {
    this.pool = pool;
    this.contexto = new AsyncLocalStorage();
  }

  cliente() {
    return this.contexto.getStore() ?? this.pool;
  }

  prepare(sql) {
    const consulta = parametrosPostgres(sql);
    return {
      get: async (...valores) => (await this.cliente().query(consulta, valores)).rows[0],
      all: async (...valores) => (await this.cliente().query(consulta, valores)).rows,
      run: async (...valores) => {
        const inserirComId = /^\s*INSERT\s+INTO\s+(unidades|historico|auditoria)\b/i.test(sql) && !/\bRETURNING\b/i.test(sql);
        const resultado = await this.cliente().query(inserirComId ? `${consulta} RETURNING id` : consulta, valores);
        return {
          changes: resultado.rowCount,
          lastInsertRowid: resultado.rows[0]?.id,
        };
      },
    };
  }

  async exec(sql) {
    await this.cliente().query(sql);
  }

  async transaction(operacao) {
    const cliente = await this.pool.connect();
    try {
      await cliente.query('BEGIN');
      const resultado = await this.contexto.run(cliente, operacao);
      await cliente.query('COMMIT');
      return resultado;
    } catch (error) {
      await cliente.query('ROLLBACK');
      throw error;
    } finally {
      cliente.release();
    }
  }

  close() {
    return this.pool.end();
  }
}

export async function abrirBanco({ pool, connectionString, configurarAuditoria = true, ...opcoes } = {}) {
  const conexao = pool ?? new Pool({
    ...(connectionString ? { connectionString } : {}),
    ...opcoes,
  });
  const db = new BancoPostgres(conexao);
  try {
    await db.exec(schema);
    if (configurarAuditoria) {
      await db.exec(`
        CREATE OR REPLACE FUNCTION bloquear_alteracao_auditoria() RETURNS TRIGGER
        LANGUAGE plpgsql AS $$
        BEGIN
          RAISE EXCEPTION 'registros de auditoria são imutáveis';
        END;
        $$;
        DROP TRIGGER IF EXISTS auditoria_sem_alteracao ON auditoria;
        CREATE TRIGGER auditoria_sem_alteracao
          BEFORE UPDATE OR DELETE ON auditoria
          FOR EACH ROW EXECUTE FUNCTION bloquear_alteracao_auditoria();
      `);
    }
    for (const distrito of DISTRITOS) {
      await db.prepare('INSERT INTO distritos (id, nome) VALUES (?, ?) ON CONFLICT (id) DO NOTHING')
        .run(distrito.id, distrito.nome);
    }
    const total = await db.prepare('SELECT COUNT(*) AS total FROM portarias').get();
    if (Number(total.total) === 0) {
      for (const portaria of portariasIniciais()) {
        await db.prepare('INSERT INTO portarias (id, payload) VALUES (?, ?)').run(portaria.id, JSON.stringify(portaria));
      }
      await db.prepare('INSERT INTO configuracao (chave, valor) VALUES (?, ?) ON CONFLICT (chave) DO UPDATE SET valor = EXCLUDED.valor')
        .run('vigente_id', 'cam-1.2');
    }
    return db;
  } catch (error) {
    await db.close();
    throw error;
  }
}
